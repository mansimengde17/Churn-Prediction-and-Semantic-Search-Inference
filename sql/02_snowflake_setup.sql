-- Snowflake data warehouse setup for churn prediction
-- Run in Snowflake SQL worksheet

USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;

-- Create dedicated database and schema
CREATE DATABASE IF NOT EXISTS CHURN_DB;
CREATE SCHEMA IF NOT EXISTS CHURN_DB.PUBLIC;

USE DATABASE CHURN_DB;
USE SCHEMA PUBLIC;

-- Raw customer churn training table
CREATE TABLE IF NOT EXISTS CUSTOMER_CHURN (
    CUSTOMER_ID       VARCHAR(20) NOT NULL,
    GENDER            VARCHAR(10),
    SENIOR_CITIZEN    NUMBER(1)   DEFAULT 0,
    PARTNER           NUMBER(1)   DEFAULT 0,
    DEPENDENTS        NUMBER(1)   DEFAULT 0,
    TENURE            NUMBER(3),
    PHONE_SERVICE     NUMBER(1)   DEFAULT 1,
    MULTIPLE_LINES    VARCHAR(25),
    INTERNET_SERVICE  VARCHAR(20),
    ONLINE_SECURITY   VARCHAR(25),
    ONLINE_BACKUP     VARCHAR(25),
    DEVICE_PROTECTION VARCHAR(25),
    TECH_SUPPORT      VARCHAR(25),
    STREAMING_TV      VARCHAR(25),
    STREAMING_MOVIES  VARCHAR(25),
    CONTRACT          VARCHAR(30),
    PAPERLESS_BILLING NUMBER(1)   DEFAULT 0,
    PAYMENT_METHOD    VARCHAR(40),
    MONTHLY_CHARGES   NUMBER(8,2),
    TOTAL_CHARGES     NUMBER(10,2),
    CHURN             NUMBER(1)   DEFAULT 0,
    CREATED_DATE      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (CUSTOMER_ID)
);

-- Churn prediction output table
CREATE TABLE IF NOT EXISTS CHURN_PREDICTIONS (
    CUSTOMER_ID        VARCHAR(20) NOT NULL,
    CHURN_PROBABILITY  NUMBER(5,4),
    CHURN_PREDICTION   NUMBER(1),
    RISK_LEVEL         VARCHAR(10),
    MODEL_VERSION      VARCHAR(20) DEFAULT '1.0.0',
    PREDICTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (CUSTOMER_ID)
);

-- Monthly churn analytics view
CREATE OR REPLACE VIEW V_MONTHLY_CHURN_RATE AS
SELECT
    DATE_TRUNC('MONTH', CREATED_DATE) AS MONTH,
    COUNT(*)                           AS TOTAL_CUSTOMERS,
    SUM(CHURN)                         AS CHURNED,
    ROUND(100.0 * SUM(CHURN) / COUNT(*), 2) AS CHURN_RATE_PCT,
    AVG(MONTHLY_CHARGES)               AS AVG_MONTHLY_CHARGES,
    AVG(TENURE)                        AS AVG_TENURE_MONTHS
FROM CUSTOMER_CHURN
GROUP BY 1
ORDER BY 1 DESC;

-- Revenue at risk view
CREATE OR REPLACE VIEW V_REVENUE_AT_RISK AS
SELECT
    p.RISK_LEVEL,
    COUNT(*)                        AS CUSTOMER_COUNT,
    SUM(c.MONTHLY_CHARGES)          AS MONTHLY_REVENUE_AT_RISK,
    AVG(p.CHURN_PROBABILITY)        AS AVG_CHURN_PROB
FROM CHURN_PREDICTIONS p
JOIN CUSTOMER_CHURN c ON p.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY p.RISK_LEVEL
ORDER BY AVG_CHURN_PROB DESC;

-- Cohort retention analysis
CREATE OR REPLACE VIEW V_COHORT_RETENTION AS
SELECT
    DATE_TRUNC('QUARTER', CREATED_DATE)              AS COHORT,
    DATEDIFF('MONTH', MIN(CREATED_DATE), MAX(CREATED_DATE)) AS MONTHS_OBSERVED,
    COUNT(*)                                          AS COHORT_SIZE,
    SUM(CHURN)                                        AS CHURNED,
    ROUND(100.0 * (1 - SUM(CHURN) / COUNT(*)), 2)    AS RETENTION_RATE_PCT
FROM CUSTOMER_CHURN
GROUP BY 1
ORDER BY 1 DESC;
